"""Web Application Firewall fingerprinting.

`detect_waf` inspects headers and body markers of one response and names
the WAF when a signature matches. Every rule is kept deliberately tight:
a page that merely *discusses* a product must not match - only the
products' own markers count (specific headers, specific server strings,
first-person block pages).
"""

from __future__ import annotations

from .http.models import HttpResponse

# (name, rules); rule shapes: ("header", name) | ("header", name, contains) | ("body", contains)
WAF_SIGNATURES: list[tuple[str, list[tuple]]] = [
    (
        "Cloudflare",
        [
            ("header", "cf-ray"),
            ("header", "cf-mitigated"),
            ("header", "server", "cloudflare"),
            ("body", "attention required! | cloudflare"),
            ("body", "cf-browser-verification"),
        ],
    ),
    ("AWS WAF", [("header", "x-amzn-waf-action"), ("body", "awswaf")]),
    ("Akamai", [("header", "akamai-grn"), ("header", "server", "akamai")]),
    ("Imperva Incapsula", [("header", "x-iinfo"), ("body", "incapsula")]),
    ("ModSecurity", [("header", "server", "mod_security"), ("header", "x-mod-security")]),
    ("Sucuri", [("header", "x-sucuri-id"), ("body", "sucuri website firewall")]),
    ("SiteLock", [("header", "x-sitelock-id"), ("body", "sitelock is a leader in business website security")]),
    ("F5 BIG-IP", [("header", "x-cnection"), ("header", "server", "bigip")]),
    ("Wordfence", [("body", "generated by wordfence")]),
]

_MAX_BODY = 20_000


def detect_waf(response: HttpResponse) -> tuple[str, str] | None:
    """Return (waf name, evidence) for the first matching signature, else None."""
    body = response.text[:_MAX_BODY].lower()
    for name, rules in WAF_SIGNATURES:
        for rule in rules:
            if rule[0] == "header":
                value = response.header(rule[1]).lower()
                if not value:
                    continue
                if len(rule) == 2:
                    return name, f"header {rule[1]}"
                if rule[2] in value:
                    return name, f"header {rule[1]}: {rule[2]}"
            elif rule[0] == "body" and rule[1] in body:
                return name, f"body marker {rule[1]!r}"
    return None
